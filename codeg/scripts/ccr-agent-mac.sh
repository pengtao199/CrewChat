#!/usr/bin/env bash
#
# [crewchat] Install / refresh the launchd agent that keeps CCR up on this machine.
#
#   bash scripts/ccr-agent-mac.sh                     # 用已存的 token（首次会生成一个）
#   CCR_WEB_AUTH_TOKEN=… bash scripts/ccr-agent-mac.sh # 指定 token
#
# 为什么需要它：**CCR 会随父进程一起死**——从终端或某个 agent 会话里起的实例，那个会话
# 一被清理它就没了（"CCR 一直不稳定"的真因）；它一死，`~/.claude-code-router/service.json`
# 也没了，双击启动的 Codeg 连"发现"都无从谈起（模型页显示未运行 / 无 token，按角色的模型
# 静默回落到 CLI 自己的）。交给 launchd 后：常驻、不随会话消失，`StartInterval` 当 watchdog
# （`ccr start` 幂等：已在跑就打印 already running 并以 0 退出）。
#
# token 固定后 `ccr start` 会把它写进 `service.json`（`url` 带 `?ccr_web_token=…`），Codeg 读它
# ——所以双击启动的 app **不需要任何环境变量**。token 落在 `~/.config/crewchat/ccr-token`
# （0600，仓库外），**不进 git**。
set -euo pipefail

# .data/ccr lives at the REPO root, one level above codeg/ (where this script is).
REPO="$(cd "$(dirname "$0")/../.." && pwd)"

CCR_CLI="$REPO/.data/ccr/node_modules/@musistudio/claude-code-router/dist/main/cli.js"
if [ ! -f "$CCR_CLI" ]; then
  echo "!! 找不到 CCR CLI：$CCR_CLI" >&2
  echo "   先在 .data/ccr 装依赖（见 AGENTS/gateway.md）。" >&2
  exit 1
fi

NODE="$(command -v node || true)"
if [ -z "$NODE" ]; then
  echo "!! 找不到 node。launchd 的 PATH 里没有它，所以 plist 里必须写绝对路径。" >&2
  exit 1
fi

TOKEN_FILE="$HOME/.config/crewchat/ccr-token"
TOKEN="${CCR_WEB_AUTH_TOKEN:-}"
if [ -z "$TOKEN" ]; then
  if [ -f "$TOKEN_FILE" ]; then
    TOKEN="$(cat "$TOKEN_FILE")"
  else
    mkdir -p "$(dirname "$TOKEN_FILE")"
    TOKEN="crewchat-ccr-$(openssl rand -hex 8)"
    printf '%s' "$TOKEN" > "$TOKEN_FILE"
    chmod 600 "$TOKEN_FILE"
    echo "== 生成了固定 token → $TOKEN_FILE（0600）=="
  fi
fi

PLIST="$HOME/Library/LaunchAgents/com.crewchat.ccr.plist"
mkdir -p "$(dirname "$PLIST")"

cat > "$PLIST" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- Generated by codeg/scripts/ccr-agent-mac.sh — edit the script, not this file. -->
<plist version="1.0">
<dict>
  <key>Label</key>
  <string>com.crewchat.ccr</string>
  <!-- node is invoked EXPLICITLY: \`ccr\` is a \`#!/usr/bin/env node\` script and
       launchd's PATH has no node (\`env: node: No such file or directory\`). -->
  <key>ProgramArguments</key>
  <array>
    <string>$NODE</string>
    <string>$CCR_CLI</string>
    <string>start</string>
    <string>--daemon</string>
    <string>--no-open</string>
  </array>
  <key>EnvironmentVariables</key>
  <dict>
    <key>CCR_WEB_AUTH_TOKEN</key>
    <string>$TOKEN</string>
  </dict>
  <key>RunAtLoad</key>
  <true/>
  <!-- Watchdog, NOT KeepAlive: \`ccr start\` daemonizes and exits, so KeepAlive would
       respawn it in a loop. Re-running it while CCR is up is a no-op. -->
  <key>StartInterval</key>
  <integer>120</integer>
  <key>StandardOutPath</key>
  <string>$HOME/Library/Logs/crewchat-ccr.log</string>
  <key>StandardErrorPath</key>
  <string>$HOME/Library/Logs/crewchat-ccr.log</string>
</dict>
</plist>
EOF

plutil -lint "$PLIST"
launchctl bootout "gui/$(id -u)/com.crewchat.ccr" 2>/dev/null || true
launchctl bootstrap "gui/$(id -u)" "$PLIST"
echo "== 已加载 launchd agent（watchdog 每 120s 一次）=="

sleep 10
echo "== 端口（管理面 3458 / 网关 3456）=="
lsof -nP -iTCP -sTCP:LISTEN 2>/dev/null | grep -E "3456|3458" | awk '{print "   ", $1, $2, $9}'
echo "== 发现文件 =="
if [ -f "$HOME/.claude-code-router/service.json" ]; then
  python3 - "$HOME/.claude-code-router/service.json" <<'PY'
import json, sys
d = json.load(open(sys.argv[1]))
print("    pid:", d.get("pid"), "| url:", d.get("url"))
PY
else
  echo "    !! service.json 还没写——看日志：$HOME/Library/Logs/crewchat-ccr.log" >&2
fi
echo "== 日志 =="
tail -3 "$HOME/Library/Logs/crewchat-ccr.log" 2>/dev/null || true
